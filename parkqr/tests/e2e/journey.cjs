const OUT=process.argv[2]||require('os').tmpdir();
const {chromium}=require('playwright');
(async()=>{const b=await chromium.launch();const errs=[];
const ctx=await b.newContext({viewport:{width:400,height:900}});const op=await ctx.newPage();op.on('pageerror',e=>errs.push(e.message));
await op.goto('http://localhost:8788/register.html');
await op.screenshot({path:OUT+'/n_reg1.png',fullPage:true});
await op.fill('#first','أحمد');await op.fill('#last','الخطيب');await op.fill('#nickname','تويوتا بيضاء');await op.fill('#phone','0795551234');await op.check('#consent');await op.click('#btn');
await op.waitForSelector('#doneView:not([hidden])');
const {token,key}=await op.evaluate(()=>window.__reg);
await op.screenshot({path:OUT+'/n_reg2.png',fullPage:true});
const s=await b.newContext({viewport:{width:400,height:900}});const sp=await s.newPage();sp.on('pageerror',e=>errs.push(e.message));
await sp.goto('http://localhost:8788/c?t='+token);await sp.waitForSelector('#pick:not([hidden])');
await sp.screenshot({path:OUT+'/n_scan.png',fullPage:true});
await sp.locator('.opt').first().click();await sp.waitForSelector('#sent:not([hidden])');
await sp.screenshot({path:OUT+'/n_sent.png',fullPage:true});
await op.goto('http://localhost:8788/inbox.html#'+key);await op.waitForSelector('.thread .chip');
await op.screenshot({path:OUT+'/n_inbox1.png',fullPage:true});
await op.click('#pauseBtn');await op.waitForTimeout(600);
console.log('paused state:',await op.getAttribute('#pauseBtn','aria-checked'),await op.textContent('#recTitle'));
await op.screenshot({path:OUT+'/n_inbox_off.png',fullPage:true});
await op.click('#pauseBtn');await op.waitForTimeout(600);
console.log('back on:',await op.getAttribute('#pauseBtn','aria-checked'),await op.textContent('#recTitle'));
await op.locator('.thread .chip',{hasText:'دقيقتين'}).click();
await sp.waitForSelector('#replyCard:not([hidden])',{timeout:9000});
console.log('sender reply:',await sp.textContent('#replyText'));
await sp.screenshot({path:OUT+'/n_reply.png',fullPage:true});
console.log('errs',errs);await b.close()})();
